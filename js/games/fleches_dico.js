export function parseDefs() {
  const out = [];
  const seen = new Set();
  for (const line of DEFS.split("\n")) {
    const i = line.indexOf(":");
    if (i < 0) continue;
    const w = line.slice(0, i).trim(), d = line.slice(i + 1).trim();
    if (!/^[A-Z]{2,9}$/.test(w) || seen.has(w)) continue;
    seen.add(w);
    out.push({ w, d });
  }
  return out;
}
